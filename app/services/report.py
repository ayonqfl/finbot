# ──────────────────────────────────────────────
#  finbot — Report Generator (PDF + CSV)
# ──────────────────────────────────────────────

import os
import pandas as pd
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (
    SimpleDocTemplate, Table, TableStyle, Paragraph,
    Spacer, HRFlowable
)
from app.core.config import REPORTS_DIR

# Ensure reports directory exists
os.makedirs(REPORTS_DIR, exist_ok=True)


def _timestamp() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


# ── CSV ────────────────────────────────────────

def generate_csv(data: list[dict], symbol: str, report_type: str) -> str:
    """
    Generate a CSV file from list of dicts.
    Returns absolute file path.
    """
    df = pd.DataFrame(data)
    filename = f"finbot_{symbol}_{report_type}_{_timestamp()}.csv"
    filepath = os.path.join(REPORTS_DIR, filename)
    df.to_csv(filepath, index=False, encoding="utf-8-sig")   # utf-8-sig for Excel compat
    return filepath


# ── PDF ────────────────────────────────────────

# Brand colours
BRAND_DARK  = colors.HexColor("#0d1117")
BRAND_BLUE  = colors.HexColor("#1e6fff")
BRAND_LIGHT = colors.HexColor("#e6edf3")
BRAND_MUTED = colors.HexColor("#8b949e")
ROW_ALT     = colors.HexColor("#161b22")

def generate_pdf(data: list[dict] | dict, symbol: str, report_type: str) -> str:
    """
    Generate a styled PDF report using ReportLab.
    Returns absolute file path.
    """
    if isinstance(data, dict):
        data = [data]

    filename = f"finbot_{symbol}_{report_type}_{_timestamp()}.pdf"
    filepath = os.path.join(REPORTS_DIR, filename)

    doc = SimpleDocTemplate(
        filepath,
        pagesize=A4,
        topMargin=1.5 * cm,
        bottomMargin=1.5 * cm,
        leftMargin=1.5 * cm,
        rightMargin=1.5 * cm,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "FinbotTitle",
        parent=styles["Heading1"],
        fontSize=20,
        textColor=BRAND_BLUE,
        spaceAfter=4,
        fontName="Helvetica-Bold",
    )
    sub_style = ParagraphStyle(
        "FinbotSub",
        parent=styles["Normal"],
        fontSize=10,
        textColor=BRAND_MUTED,
        spaceAfter=2,
        fontName="Helvetica",
    )
    label_style = ParagraphStyle(
        "FinbotLabel",
        parent=styles["Normal"],
        fontSize=9,
        textColor=BRAND_MUTED,
        fontName="Helvetica",
    )

    elements = []

    # ── Header
    elements.append(Paragraph("🤖 finbot", title_style))
    elements.append(Paragraph("Bangladesh OMS Financial Chatbot", sub_style))
    elements.append(HRFlowable(width="100%", thickness=1, color=BRAND_BLUE, spaceAfter=6))

    # ── Report meta
    report_label = report_type.replace("_", " ").title()
    generated_at = datetime.now().strftime("%d %b %Y %H:%M")
    elements.append(Paragraph(f"<b>Symbol:</b> {symbol}", sub_style))
    elements.append(Paragraph(f"<b>Report:</b> {report_label}", sub_style))
    elements.append(Paragraph(f"<b>Generated:</b> {generated_at}", label_style))
    elements.append(Spacer(1, 0.4 * cm))

    # ── Data table
    if data:
        df = pd.DataFrame(data)
        # Replace None/NaN with "-"
        df = df.fillna("-")

        headers = list(df.columns)
        table_data = [headers] + df.values.tolist()

        col_widths = [A4[0] / len(headers) - 0.3 * cm] * len(headers)

        tbl = Table(table_data, colWidths=col_widths, repeatRows=1)
        tbl.setStyle(TableStyle([
            # Header row
            ("BACKGROUND",    (0, 0), (-1, 0), BRAND_BLUE),
            ("TEXTCOLOR",     (0, 0), (-1, 0), colors.white),
            ("FONTNAME",      (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE",      (0, 0), (-1, 0), 9),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
            ("TOPPADDING",    (0, 0), (-1, 0), 6),
            # Data rows
            ("FONTSIZE",      (0, 1), (-1, -1), 8),
            ("FONTNAME",      (0, 1), (-1, -1), "Helvetica"),
            ("TEXTCOLOR",     (0, 1), (-1, -1), BRAND_DARK),
            ("ROWBACKGROUNDS",(0, 1), (-1, -1), [colors.white, colors.HexColor("#f0f4f8")]),
            ("GRID",          (0, 0), (-1, -1), 0.4, colors.HexColor("#d0d7de")),
            ("VALIGN",        (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING",   (0, 0), (-1, -1), 5),
            ("RIGHTPADDING",  (0, 0), (-1, -1), 5),
        ]))
        elements.append(tbl)

    elements.append(Spacer(1, 0.5 * cm))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=BRAND_MUTED))
    elements.append(Paragraph(
        "Generated by finbot — Data sourced from stockdb. For informational purposes only.",
        label_style
    ))

    doc.build(elements)
    return filepath
